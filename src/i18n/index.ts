const dictionaries: Record<AppLanguage, Record<TranslationKey, string>> = { en, tr };

function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/{{(\w+)}}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  );
}

export function translate(language: AppLanguage, key: TranslationKey, params?: Params): string {
  return interpolate(dictionaries[language][key] ?? en[key] ?? key, params);
}

