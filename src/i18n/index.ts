export function translateGameText(value: string, language: AppLanguage): string {
  if (language === 'en') return value;
  return gameTextTr[value] ?? value;
}

export function translateGameValue(value: unknown, language: AppLanguage): string {
  if (Array.isArray(value)) {
    return value.map((item) => translateGameValue(item, language)).join(', ');
  }
  if (value && typeof value === 'object') {
    return Object.entries(value as Record<string, unknown>)
      .map(([key, entry]) => `${translateGameText(key, language)}: ${translateGameValue(entry, language)}`)
      .join(', ');
  }
  return translateGameText(String(value), language);
}

export function useTranslation() {
  const language = useSettingsStore((state) => state.language);
  const t = useCallback(
    (key: TranslationKey, params?: Params) => translate(language, key, params),
    [language],
  );
  const gameText = useCallback((value: string) => translateGameText(value, language), [language]);
  const gameValue = useCallback((value: unknown) => translateGameValue(value, language), [language]);
  return { language, t, gameText, gameValue } as const;
}
